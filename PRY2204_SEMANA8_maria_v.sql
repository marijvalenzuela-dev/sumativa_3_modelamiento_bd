CREATE TABLE MARCA (
id_marca NUMBER (2),
descripcion VARCHAR2 (20) NOT NULL
);

CREATE TABLE MODELO (
id_modelo NUMBER (5),
marca_id NUMBER (2),
descripcion VARCHAR2 (20) NOT NULL
);

CREATE TABLE TIPO_AUTOMOVIL (
id_tipo CHAR(3),
